// Segment → binary STL for 3D printing (Slicer export conventions: closed surface, LPS, SPACE= header).
// Pure TS — no vtk.js. Marching cubes on a padded binary mask, IJK→RAS via ijkToRAS, then RAS→LPS.

export type StlSegment = { num: number; name: string; color: [number, number, number] };

const OVERLAY_CSS =
  "position:fixed;inset:0;z-index:2000;background:rgba(5,6,10,.85);display:flex;align-items:center;justify-content:center;";
const CARD_CSS =
  "background:#11141d;border:1px solid #33507e;border-radius:10px;padding:20px 24px;width:420px;max-width:92vw;max-height:80vh;overflow:auto;font:13px -apple-system,system-ui,sans-serif;color:#d6e2f2;";

/** Sanitize a segment name for a download filename (Slicer GetSafeFileName spirit). */
export function safeStlFileName(name: string): string {
  const s = name.replace(/[^\w.\-]+/g, "_").replace(/^_+|_+$/g, "").slice(0, 80);
  return (s || "segment") + ".stl";
}

/** Trigger a browser download of a binary STL buffer. */
export function downloadStl(buffer: ArrayBuffer, filename: string): void {
  const blob = new Blob([buffer], { type: "model/stl" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

/**
 * Pick a segment from a list, then run `onPick`. Overlay matches idc-share styling.
 * Resolves after pick or cancel (cancel → undefined).
 */
export function pickSegment(segments: StlSegment[]): Promise<StlSegment | undefined> {
  return new Promise((resolve) => {
    if (document.getElementById("seg-stl-pick")) {
      resolve(undefined);
      return;
    }
    const overlay = document.createElement("div");
    overlay.id = "seg-stl-pick";
    overlay.style.cssText = OVERLAY_CSS;
    const rows = segments
      .map((s) => {
        const [r, g, b] = s.color.map((c) => Math.round(c * 255));
        const swatch =
          `display:inline-block;width:12px;height:12px;border-radius:2px;margin-right:8px;` +
          `background:rgb(${r},${g},${b});vertical-align:middle;`;
        return `<button type="button" data-num="${s.num}" style="display:block;width:100%;text-align:left;
          font:600 13px -apple-system,system-ui,sans-serif;color:#d6e2f2;background:#0b0e16;
          border:1px solid #1b2740;border-radius:6px;padding:10px 12px;margin:0 0 6px;cursor:pointer;">
          <span style="${swatch}"></span>${escapeHtml(s.name)}
          <span style="color:#5a6b85;font-weight:500;margin-left:6px;">#${s.num}</span>
        </button>`;
      })
      .join("");
    overlay.innerHTML = `
      <div style="${CARD_CSS}">
        <h3 style="margin:0 0 4px;color:#fff;">Save segment as STL</h3>
        <p style="margin:0 0 14px;color:#9fb3d0;">Binary STL in LPS (3D-print convention). Pick a segment:</p>
        <div id="seg-stl-list">${rows}</div>
        <div style="text-align:right;margin-top:10px;">
          <button type="button" id="seg-stl-cancel" style="font:600 12px -apple-system,system-ui,sans-serif;
            color:#9fb3d0;background:none;border:none;cursor:pointer;padding:6px 4px;">Cancel</button>
        </div>
      </div>`;
    document.body.appendChild(overlay);
    const done = (seg?: StlSegment) => {
      overlay.remove();
      resolve(seg);
    };
    overlay.querySelector("#seg-stl-cancel")!.addEventListener("click", () => done());
    overlay.addEventListener("click", (e) => {
      if (e.target === overlay) done();
    });
    overlay.querySelectorAll<HTMLButtonElement>("#seg-stl-list button").forEach((btn) => {
      btn.addEventListener("click", () => {
        const num = Number(btn.dataset.num);
        done(segments.find((s) => s.num === num));
      });
      btn.addEventListener("mouseenter", () => {
        btn.style.borderColor = "#2b6cb0";
        btn.style.background = "#151a28";
      });
      btn.addEventListener("mouseleave", () => {
        btn.style.borderColor = "#1b2740";
        btn.style.background = "#0b0e16";
      });
    });
  });
}

function escapeHtml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

/**
 * Extract a closed surface for one label and write a binary STL (LPS, header SPACE=LPS).
 * Matches Slicer ExportSegmentsClosedSurfaceRepresentationToStlFiles conventions for coords/header.
 */
export function segmentToStl(
  lab: Uint8Array,
  dims: [number, number, number],
  ijkToRAS: number[],
  segmentNum: number,
): ArrayBuffer {
  const [nx, ny, nz] = dims;
  if (lab.length !== nx * ny * nz) {
    throw new Error(`labelmap size ${lab.length} != dims ${nx}×${ny}×${nz}`);
  }

  // Bounding box of the label
  let i0 = nx, j0 = ny, k0 = nz, i1 = -1, j1 = -1, k1 = -1;
  for (let k = 0; k < nz; k++) {
    for (let j = 0; j < ny; j++) {
      const base = (k * ny + j) * nx;
      for (let i = 0; i < nx; i++) {
        if (lab[base + i] !== segmentNum) continue;
        if (i < i0) i0 = i;
        if (j < j0) j0 = j;
        if (k < k0) k0 = k;
        if (i > i1) i1 = i;
        if (j > j1) j1 = j;
        if (k > k1) k1 = k;
      }
    }
  }
  if (i1 < 0) throw new Error(`segment ${segmentNum} is empty`);

  // 1-voxel pad (Slicer closes surfaces that touch the labelmap border)
  const x0 = i0 - 1, y0 = j0 - 1, z0 = k0 - 1;
  const x1 = i1 + 1, y1 = j1 + 1, z1 = k1 + 1;
  const sx = x1 - x0 + 1, sy = y1 - y0 + 1, sz = z1 - z0 + 1;
  const mask = new Uint8Array(sx * sy * sz);
  for (let k = 0; k < sz; k++) {
    const gk = k + z0;
    for (let j = 0; j < sy; j++) {
      const gj = j + y0;
      for (let i = 0; i < sx; i++) {
        const gi = i + x0;
        if (gi < 0 || gj < 0 || gk < 0 || gi >= nx || gj >= ny || gk >= nz) continue;
        if (lab[(gk * ny + gj) * nx + gi] === segmentNum) mask[(k * sy + j) * sx + i] = 1;
      }
    }
  }

  const tris = marchingCubes(mask, sx, sy, sz, x0, y0, z0);
  if (!tris.length) throw new Error(`segment ${segmentNum}: no surface triangles`);

  // IJK → RAS → LPS (Slicer default for STL print export)
  const M = ijkToRAS;
  const lps: number[] = new Array(tris.length);
  for (let t = 0; t < tris.length; t += 9) {
    for (let v = 0; v < 3; v++) {
      const i = tris[t + v * 3], j = tris[t + v * 3 + 1], k = tris[t + v * 3 + 2];
      const rx = M[0] * i + M[1] * j + M[2] * k + M[3];
      const ry = M[4] * i + M[5] * j + M[6] * k + M[7];
      const rz = M[8] * i + M[9] * j + M[10] * k + M[11];
      lps[t + v * 3] = -rx;
      lps[t + v * 3 + 1] = -ry;
      lps[t + v * 3 + 2] = rz;
    }
  }

  return writeBinaryStl(lps, "SlicerLive IRA. SPACE=LPS");
}

/** Binary STL: 80-byte header + uint32 count + 50 bytes/triangle (little-endian). */
function writeBinaryStl(flatTris: number[], headerText: string): ArrayBuffer {
  const nTri = (flatTris.length / 9) | 0;
  const buf = new ArrayBuffer(84 + nTri * 50);
  const u8 = new Uint8Array(buf);
  const dv = new DataView(buf);
  const hdr = new TextEncoder().encode(headerText.slice(0, 79));
  u8.set(hdr, 0);
  dv.setUint32(80, nTri, true);
  let off = 84;
  for (let t = 0; t < nTri; t++) {
    const b = t * 9;
    const ax = flatTris[b], ay = flatTris[b + 1], az = flatTris[b + 2];
    const bx = flatTris[b + 3], by = flatTris[b + 4], bz = flatTris[b + 5];
    const cx = flatTris[b + 6], cy = flatTris[b + 7], cz = flatTris[b + 8];
    // facet normal (right-hand); zero-length ok for many slicers
    let nx = (by - ay) * (cz - az) - (bz - az) * (cy - ay);
    let ny = (bz - az) * (cx - ax) - (bx - ax) * (cz - az);
    let nz = (bx - ax) * (cy - ay) - (by - ay) * (cx - ax);
    const len = Math.hypot(nx, ny, nz) || 1;
    nx /= len;
    ny /= len;
    nz /= len;
    dv.setFloat32(off, nx, true);
    dv.setFloat32(off + 4, ny, true);
    dv.setFloat32(off + 8, nz, true);
    dv.setFloat32(off + 12, ax, true);
    dv.setFloat32(off + 16, ay, true);
    dv.setFloat32(off + 20, az, true);
    dv.setFloat32(off + 24, bx, true);
    dv.setFloat32(off + 28, by, true);
    dv.setFloat32(off + 32, bz, true);
    dv.setFloat32(off + 36, cx, true);
    dv.setFloat32(off + 40, cy, true);
    dv.setFloat32(off + 44, cz, true);
    dv.setUint16(off + 48, 0, true);
    off += 50;
  }
  return buf;
}

